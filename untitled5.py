import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf
from tensorflow.keras import layers, models
from datasets import load_dataset
from sklearn.model_selection import train_test_split
from sklearn.metrics import (classification_report, confusion_matrix,
                             ConfusionMatrixDisplay, roc_curve, auc)

# ---------- 1. Load data (4000 random images, resized to 64x64) ----------
N, SIZE = 4000, (64, 64)
ds = load_dataset("microsoft/cats_vs_dogs", split="train")
ds = ds.shuffle(seed=42).select(range(N))

label_col = "labels" if "labels" in ds.column_names else "label"
class_names = ds.features[label_col].names          # ['cat', 'dog']
print("Classes:", class_names)

X, y = [], []
for ex in ds:
    try:
        img = ex["image"].convert("RGB").resize(SIZE)
        X.append(np.array(img, dtype="float32"))
        y.append(ex[label_col])
    except Exception:
        pass                                         # skip any corrupt image
X, y = np.array(X), np.array(y)
print("Images:", X.shape, "| cats:", (y == 0).sum(), "dogs:", (y == 1).sum())

X_train, X_val, y_train, y_val = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=42)

# ---------- 2. Build a simple CNN ----------
model = models.Sequential([
    layers.Input(shape=(64, 64, 3)),
    layers.Rescaling(1.0 / 255),
    layers.Conv2D(16, 3, activation="relu"), layers.MaxPooling2D(),
    layers.Conv2D(32, 3, activation="relu"), layers.MaxPooling2D(),
    layers.Conv2D(64, 3, activation="relu"), layers.MaxPooling2D(),
    layers.Flatten(),
    layers.Dropout(0.3),
    layers.Dense(64, activation="relu"),
    layers.Dense(1, activation="sigmoid"),           # 0 = cat, 1 = dog
])
model.compile(optimizer="adam", loss="binary_crossentropy", metrics=["accuracy"])

# ---------- 3. Train ----------
history = model.fit(X_train, y_train, validation_data=(X_val, y_val),
                    epochs=8, batch_size=32)

# ---------- 4. Loss and accuracy graphs ----------
fig, ax = plt.subplots(1, 2, figsize=(11, 4))
ax[0].plot(history.history["accuracy"], label="train")
ax[0].plot(history.history["val_accuracy"], label="validation")
ax[0].set_title("Accuracy"); ax[0].set_xlabel("Epoch"); ax[0].legend()
ax[1].plot(history.history["loss"], label="train")
ax[1].plot(history.history["val_loss"], label="validation")
ax[1].set_title("Loss"); ax[1].set_xlabel("Epoch"); ax[1].legend()
plt.tight_layout(); plt.show()

# ---------- 5. Predictions ----------
probs = model.predict(X_val, verbose=0).ravel()
y_pred = (probs > 0.5).astype(int)

# ---------- 6. Classification report ----------
print("\nCLASSIFICATION REPORT")
print(classification_report(y_val, y_pred, target_names=class_names))

# ---------- 7. ROC-AUC graph and confusion matrix ----------
fpr, tpr, _ = roc_curve(y_val, probs)
roc_auc = auc(fpr, tpr)

fig, ax = plt.subplots(1, 2, figsize=(11, 4.5))
ax[0].plot(fpr, tpr, color="darkorange", lw=2, label=f"AUC = {roc_auc:.3f}")
ax[0].plot([0, 1], [0, 1], "k--")
ax[0].set_title("ROC Curve"); ax[0].set_xlabel("False Positive Rate")
ax[0].set_ylabel("True Positive Rate"); ax[0].legend(loc="lower right")
ConfusionMatrixDisplay(confusion_matrix(y_val, y_pred),
                       display_labels=class_names).plot(ax=ax[1], cmap="Blues", colorbar=False)
ax[1].set_title("Confusion Matrix")
plt.tight_layout(); plt.show()

# ---------- 8. Cat vs Dog predictions on sample images ----------
idx = np.random.RandomState(0).choice(len(X_val), 8, replace=False)
plt.figure(figsize=(12, 6))
for k, i in enumerate(idx):
    conf = probs[i] if y_pred[i] == 1 else 1 - probs[i]
    plt.subplot(2, 4, k + 1)
    plt.imshow(X_val[i].astype("uint8"))
    plt.title(f"{class_names[y_pred[i]]} ({conf * 100:.0f}%)",
              color="green" if y_pred[i] == y_val[i] else "red")
    plt.axis("off")
plt.suptitle("Predictions (green = correct, red = wrong)")
plt.tight_layout(); plt.show()

print(f"Final validation accuracy: {(y_pred == y_val).mean() * 100:.2f}%   |   AUC: {roc_auc:.3f}")